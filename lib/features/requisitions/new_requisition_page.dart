import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:go_router/go_router.dart';

import '../../core/models.dart';
import '../../core/state.dart';
import '../../core/theme/bv_theme.dart';
import '../../core/widgets.dart';

const kSchoolDepartments = [
  'Science', 'Mathematics', 'Humanities', 'Languages', 'Sports', 'Administration',
  'Boarding', 'Kitchen / Dining', 'Library', 'ICT', 'Facilities', 'Matron',
];

class _Line {
  Item? item;
  final qty = TextEditingController(text: '1');
  final note = TextEditingController();
  final Key key = UniqueKey();
  void dispose() {
    qty.dispose();
    note.dispose();
  }
}

class NewRequisitionPage extends ConsumerStatefulWidget {
  const NewRequisitionPage({super.key});
  @override
  ConsumerState<NewRequisitionPage> createState() => _NewRequisitionPageState();
}

class _NewRequisitionPageState extends ConsumerState<NewRequisitionPage> {
  final _form = GlobalKey<FormState>();
  final _purpose = TextEditingController();
  final _diners = TextEditingController();
  final _lines = <_Line>[_Line()];
  String _dept = 'Science';
  bool _kitchen = false, _busy = false;

  @override
  void dispose() {
    _purpose.dispose();
    _diners.dispose();
    for (final l in _lines) {
      l.dispose();
    }
    super.dispose();
  }

  Future<void> _save() async {
    if (!_form.currentState!.validate()) return;
    final me = ref.read(sessionProvider)!;
    final diners = int.tryParse(_diners.text) ?? 0;
    final lines = <({int itemId, int qty, String uom, String description})>[];
    for (final l in _lines) {
      final q = int.tryParse(l.qty.text) ?? 0;
      if (l.item == null || q < 1) continue;
      var desc = l.note.text.trim();
      if (_kitchen && diners > 0) {
        final per = (q / diners).toStringAsFixed(3);
        desc = '${desc.isEmpty ? '' : '$desc. '}Per diner: $per ${l.item!.uom}';
      }
      lines.add((itemId: l.item!.id, qty: q, uom: l.item!.uom, description: desc));
    }
    if (lines.isEmpty) {
      snack(context, 'Add at least one item with a quantity.');
      return;
    }
    final purpose = _kitchen
        ? 'Kitchen requisition (BVC-BOP-KIT-017). Bona fide diners: $diners. ${_purpose.text.trim()}'
        : _purpose.text.trim();
    setState(() => _busy = true);
    final ok = await act(context, ref,
        () => ref.read(repoProvider).createRequisition(department: _dept, officer: me.name, purpose: purpose, lines: lines),
        'Requisition sent to the Stores Controller.');
    if (!mounted) return;
    setState(() => _busy = false);
    if (ok) context.go('/app/requisitions');
  }

  @override
  Widget build(BuildContext context) {
    final me = ref.watch(sessionProvider);
    if (me == null) return const SizedBox();
    final items = ref.watch(itemsP);
    final bal = ref.watch(balancesP);
    final onHand = bal.valueOrNull == null ? <int, double>{} : onHandByItem(bal.valueOrNull!);

    return PageBody(
      title: 'New item requisition',
      subtitle: 'The number is generated by the server (BVC-REQ-YYYY-#####).',
      actions: [
        OutlinedButton(style: canvasOutlined(context), onPressed: () => context.go('/app/requisitions'), child: const Text('Cancel')),
      ],
      children: [
        AsyncBody<List<Item>>(
          value: items,
          onRetry: () => ref.invalidate(itemsP),
          builder: (catalogue) => catalogue.isEmpty
              ? const Panel(child: Text('The item catalogue is empty. Ask the Stores Controller to add items first (Catalogue).'))
              : Form(
                  key: _form,
                  child: Column(children: [
                    Panel(
                      title: 'Details',
                      child: Column(children: [
                        Wrap(spacing: 16, runSpacing: 12, children: [
                          SizedBox(
                            width: 260,
                            child: DropdownButtonFormField<String>(
                              value: _dept,
                              decoration: const InputDecoration(labelText: 'Department'),
                              items: [for (final d in kSchoolDepartments) DropdownMenuItem(value: d, child: Text(d))],
                              onChanged: (v) => setState(() {
                                _dept = v ?? _dept;
                                _kitchen = _dept == 'Kitchen / Dining' ? true : _kitchen;
                              }),
                            ),
                          ),
                          SizedBox(
                            width: 260,
                            child: InputDecorator(
                              decoration: const InputDecoration(labelText: 'Requesting officer'),
                              child: Text(me.name),
                            ),
                          ),
                        ]),
                        const SizedBox(height: 12),
                        TextFormField(
                          controller: _purpose,
                          minLines: 2,
                          maxLines: 4,
                          maxLength: 900,
                          decoration: const InputDecoration(labelText: 'Purpose', hintText: 'Why is this needed?'),
                          validator: (v) => (v == null || v.trim().length < 5) ? 'Please explain the need.' : null,
                        ),
                        SwitchListTile(
                          contentPadding: EdgeInsets.zero,
                          title: const Text('Kitchen / dining requisition'),
                          subtitle: const Text('Must state the number of bona fide diners it supports (FRM-23).'),
                          value: _kitchen,
                          onChanged: (v) => setState(() => _kitchen = v),
                        ),
                        if (_kitchen)
                          SizedBox(
                            width: 260,
                            child: TextFormField(
                              controller: _diners,
                              keyboardType: TextInputType.number,
                              onChanged: (_) => setState(() {}),
                              decoration: const InputDecoration(labelText: 'Bona fide diners'),
                              validator: (v) => _kitchen && (int.tryParse(v ?? '') ?? 0) < 1 ? 'Required for kitchen requisitions' : null,
                            ),
                          ),
                      ]),
                    ),
                    const SizedBox(height: 16),
                    Panel(
                      title: 'Items',
                      child: Column(children: [
                        for (var i = 0; i < _lines.length; i++) _lineCard(catalogue, onHand, i),
                        Align(
                          alignment: Alignment.centerLeft,
                          child: TextButton.icon(
                            onPressed: () => setState(() => _lines.add(_Line())),
                            icon: const Icon(Icons.add_rounded),
                            label: const Text('Add item'),
                          ),
                        ),
                      ]),
                    ),
                  ]),
                ),
        ),
        Align(
          alignment: Alignment.centerRight,
          child: FilledButton(
            style: ctaStyle(context),
            onPressed: _busy ? null : _save,
            child: Text(_busy ? 'Sending...' : 'Submit to Stores Controller'),
          ),
        ),
      ],
    );
  }

  Widget _lineCard(List<Item> catalogue, Map<int, double> onHand, int i) {
    final l = _lines[i];
    final q = int.tryParse(l.qty.text) ?? 0;
    final have = l.item == null ? null : (onHand[l.item!.id] ?? 0);
    return Builder(key: l.key, builder: (c) {
      final t = Theme.of(c);
      final diners = int.tryParse(_diners.text) ?? 0;
      return Container(
        margin: const EdgeInsets.only(bottom: 12),
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(color: t.colorScheme.surfaceContainerLow, borderRadius: BorderRadius.circular(12)),
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          DropdownButtonFormField<int>(
            value: l.item?.id,
            isExpanded: true,
            decoration: InputDecoration(labelText: 'Item ${i + 1}'),
            items: [for (final it in catalogue) DropdownMenuItem(value: it.id, child: Text('${it.label} (${it.uom})'))],
            onChanged: (v) => setState(() => l.item = catalogue.firstWhere((x) => x.id == v)),
            validator: (v) => v == null ? 'Choose an item' : null,
          ),
          const SizedBox(height: 8),
          Wrap(spacing: 12, runSpacing: 8, crossAxisAlignment: WrapCrossAlignment.center, children: [
            SizedBox(
              width: 110,
              child: TextFormField(
                controller: l.qty,
                keyboardType: TextInputType.number,
                onChanged: (_) => setState(() {}),
                decoration: const InputDecoration(labelText: 'Quantity'),
                validator: (v) => (int.tryParse(v ?? '') ?? 0) < 1 ? 'Min 1' : null,
              ),
            ),
            SizedBox(
              width: 220,
              child: TextFormField(controller: l.note, decoration: const InputDecoration(labelText: 'Note (optional)')),
            ),
            if (have != null) ...[
              Text('On hand: ${qty(have)} ${l.item!.uom}'),
              StatusChip(have <= 0 ? 'NONE' : (have < q ? 'LOW' : 'OK'),
                  have <= 0 ? StatusKind.danger : (have < q ? StatusKind.pending : StatusKind.success)),
            ],
            if (_kitchen && diners > 0 && q > 0) Text('Per diner: ${(q / diners).toStringAsFixed(3)}'),
            if (_lines.length > 1)
              IconButton(
                tooltip: 'Remove',
                onPressed: () => setState(() => _lines.removeAt(i).dispose()),
                icon: Icon(Icons.delete_outline_rounded, color: t.colorScheme.error),
              ),
          ]),
        ]),
      );
    });
  }
}
